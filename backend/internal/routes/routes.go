package routes

import (
	"github.com/gin-gonic/gin"
	swaggerFiles "github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"
	"go.uber.org/zap"

	"github.com/RedShawn258/FinTrack/backend/internal/cache"
	_ "github.com/RedShawn258/FinTrack/backend/internal/docs" // docs is generated by Swag CLI
	"github.com/RedShawn258/FinTrack/backend/internal/handlers"
	"github.com/RedShawn258/FinTrack/backend/internal/middlewares"
)

func SetupRoutes(router *gin.Engine, logger *zap.Logger, jwtSecret string, cacheService *cache.CacheService) {
	// Note: Logger and JWT secret are already set in main.go middleware
	// No need to set them again here

	// Health check endpoints (public, no auth required)
	router.GET("/health", handlers.HealthHandler)
	router.GET("/health/ready", handlers.ReadinessHandler)

	// Swagger documentation endpoint
	router.GET("/docs/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))
	router.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))

	// Prometheus metrics endpoint (for outbox metrics)
	router.GET("/metrics", handlers.MetricsHandler)

	// Accounts/Ledger endpoints (public, no auth required for demo)
	accounts := router.Group("/accounts")
	{
		accounts.POST("", handlers.CreateAccount)
		accounts.GET("/:id/balance", handlers.GetAccountBalance)
		accounts.GET("/:id/ledger", handlers.GetAccountLedger)
	}

	// Ledger transaction endpoint (public, no auth required for demo)
	router.POST("/transactions", handlers.CreateLedgerTransaction)

	// Transfer endpoint (double-entry accounting)
	router.POST("/transfers", handlers.CreateTransfer)

	// Public endpoints for authentication
	auth := router.Group("/api/v1/auth")
	{
		auth.POST("/register", handlers.RegisterHandler)
		auth.POST("/login", handlers.LoginHandler)
		auth.POST("/refresh", handlers.RefreshTokenHandler)
		auth.POST("/forgot-password", handlers.ForgotPasswordHandler)
		auth.POST("/reset-password", handlers.ResetPasswordHandler)
	}

	// Protected endpoints (JWT required)
	protected := router.Group("/api/v1")
	protected.Use(middlewares.AuthMiddleware())
	{
		// Profile endpoints
		protected.GET("/profile", handlers.GetProfileHandler)
		protected.PUT("/profile", handlers.UpdateProfileHandler)
		protected.POST("/profile/image", handlers.ProfileImageUploadHandler)

		// Budget endpoints
		protected.POST("/budgets", handlers.CreateBudget)
		protected.GET("/budgets", handlers.GetBudgets)
		protected.GET("/budgets/:month", handlers.GetBudgetSummary)
		protected.PUT("/budgets/:id", handlers.UpdateBudget)
		protected.DELETE("/budgets/:id", handlers.DeleteBudget)

		// Category endpoints
		protected.GET("/categories", handlers.GetCategories)
		protected.DELETE("/categories/:id", handlers.DeleteCategory)

		// Admin-only endpoints
		admin := protected.Group("")
		admin.Use(middlewares.RequireRole("admin"))
		{
			// Category management (admin only)
			admin.POST("/categories", handlers.CreateCategory)

			// User management (admin only)
			// admin.GET("/users", handlers.GetUsers) // TODO: implement GetUsers handler
		}

		// Transaction endpoints
		protected.POST("/transactions", handlers.CreateTransaction)
		protected.GET("/transactions", handlers.GetTransactions)
		protected.GET("/transactions/summary", handlers.GetTransactionSummary)
		protected.PUT("/transactions/:id", handlers.UpdateTransaction)
		protected.DELETE("/transactions/:id", handlers.DeleteTransaction)

		// Future feature endpoints (stub implementations)
		protected.GET("/features/gamification", handlers.GamificationHandler)
		protected.GET("/features/analytics", handlers.AnalyticsHandler)
		protected.GET("/features/notifications", handlers.NotificationHandler)

		// Forecasting feature
		protected.POST("/forecast/expenses", handlers.ForecastExpensesHandler)
	}
}
